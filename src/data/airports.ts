export function loadRegionalAirports(): Promise<Airport[]> {
  regionalPromise ??= fetch('/data/airports-regional.json')
    .then((response) => (response.ok ? response.json() as Promise<AirportTuple[]> : []))
    .then((tuples) => tuples.map((tuple) => fromTuple(tuple, 2)))
    .catch(() => []);
  return regionalPromise;
}
